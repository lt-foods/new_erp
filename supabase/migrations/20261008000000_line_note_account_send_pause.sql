-- LINE 記事本：帳號被 LINE 暫時限制使用社群時，先停一段時間再自動重試
--
-- 背景（2026-10-08）：
--   早上 08:00 結單提醒一口氣把 26 團 × 9 個社群（234 則）分享到聊天室，三個帳號各送了
--   ~43 則（約 97 秒）之後同時被 LINE 擋下：
--     code=403「因違反服務條款，您已被限制使用社群。」（errorExtraInfo.userRestrictionInfo）
--   限制大約 5 分鐘（08:01:37 ～ 08:06:30）後自己解除，但這段時間 worker 照樣一張一張撿，
--   排在後面的 78 篇開團貼文全部被標「發文失敗」，之後沒有任何東西會再重發 →
--   10 個新團在 8 個社群裡沒有貼文、客人沒地方 +1。
--   同一個錯誤 10/1（帳號 3，~121 則提醒後）、10/5（帳號 13，~80 則後，之後 4 分鐘又硬打了 500 次）
--   也出現過。發文本身（每帳號每分鐘 ~25 篇）從來沒觸發過，觸發的都是「分享到聊天室」的爆量。
--
-- 這支只加一欄，邏輯在 line-note-worker：
--   - 撞到限制 → 這個帳號 send_paused_until = now() + 10 分鐘，期間不撿它的發文／分享／留言類工作；
--     撞到的那筆工作退回 queued（不標失敗），貼文列維持「排隊中」並寫明原因。
--   - 分享到聊天室（remind / share）每個帳號每分鐘最多 12 則，不再一口氣送完。
--
-- rollback：ALTER TABLE line_note_accounts DROP COLUMN send_paused_until;
--           （worker 讀不到這欄時當作沒有暫停，舊版 worker 也不會讀它）
-- ============================================================================

ALTER TABLE line_note_accounts
  ADD COLUMN IF NOT EXISTS send_paused_until TIMESTAMPTZ;

COMMENT ON COLUMN line_note_accounts.send_paused_until IS
  'LINE 回「已被限制使用社群」(code=403) 時，worker 暫停這個帳號的發文／分享／留言到這個時間；NULL 或已過＝正常';
