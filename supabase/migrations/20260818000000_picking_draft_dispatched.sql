-- ============================================================
-- 撿貨草稿：記下「這張已經送到派貨工作台了」
--
-- 老闆 2026-08-18 原話：
--   「派貨工作台的商品拉出來的數量是多少就多少，跟草稿無關，
--     我主要是草稿撿的商品可以一鍵帶回，到第一步的挑選商品」
--
-- 痛點：草稿已經挑好 40 幾樣，拿紙到派貨工作台還要一樣一樣重新找。
-- 新流程：草稿頁按【📤 送到派貨工作台】→ 只把**商品清單**帶過去（⛔ 一個數字都不帶），
--         停在派貨工作台的步驟 1（挑選商品），數量由派貨工作台自己算。
--
-- ⭐ 為什麼要這兩個欄位（老闆 2026-08-18 定案「送出後不能再送第二次」）：
--   送出這個動作本身沒有留下任何痕跡 —— 商品清單是「帶過去讓人挑」，
--   派貨工作台不會回寫草稿，草稿這邊也沒有任何欄位看得出「送過了沒」。
--   沒有這兩欄的話，同一張草稿按兩次就會把同一批商品再灌一次已挑清單，
--   而老闆在兩次之間手動取消掉的勾選會被靜默還原（他不會知道）。
--
--   dispatched_at 同時是**擋重送的條件本身**：前端下的是
--     UPDATE ... WHERE id = ? AND dispatched_at IS NULL   （並看回傳列數）
--   條件寫在語句裡而不是寫在畫面上 —— 兩台 iPad 同時按也只會有一台成功
--   （另一台的畫面是幾秒前的快照，前端擋不住這種時間差）。
--   作法沿用草稿列表頁刪除鈕的 .eq("status","draft") 那一招。
--
-- ⚠ 為什麼「重新開啟」不清空 dispatched_at：
--   老闆要的是「不能重複轉」。status 是「這張草稿還要不要改」，
--   dispatched_at 是「這批商品有沒有被帶進工作台過」—— 兩件事，刻意不連動。
--   把草稿重新開啟繼續改是合理的；再送一次不是。
--
-- ⚠ 一定要一起改 picking_drafts.status 的 COMMENT：
--   20260817000010_picking_draft_status_comment.sql 現在寫著
--     「草稿不會轉出到派貨工作台：…由人工拿紙本在派貨工作台重新挑商品」
--   —— 那是 2026-08-17 的裁示，**今天起就是錯的**（老闆 2026-08-18 改了主意，
--   理由是「只帶商品、不帶數量」把當初放棄的那六條風險全部消掉了）。
--   過期的註解比沒有註解更危險：它是**看起來有出處**的錯誤資訊，
--   下一個人會照著它去跟老闆解釋一個系統早就有的功能「我們刻意不做」。
--   本專案已經被過期註解坑過（月結引擎檔頭的舊口徑）。
--
-- ⛔⛔ 本檔的範圍（與 20260817000000 檔頭同一條原則）：
--   全檔只有 **一道 ALTER TABLE（對草稿功能自己建的 picking_drafts）＋ 三道 COMMENT**。
--   不新增 FUNCTION / RPC、不動 RLS 與權限、不建索引、不碰任何既有物件、不改任何一列資料。
--   新欄位可為空、無預設值 → 既有列原封不動，Postgres 不重寫整張表。
--   picking_drafts 的 RLS 是單一 FOR ALL policy（20260817000000），
--   新欄位自動被同一條 policy 蓋到，⛔ 不需要、也沒有新增任何 policy。
--
-- ⓘ 用 IF NOT EXISTS 是為了讓老闆**重貼一次也不會出錯**，不必先跑一支查詢確認套過沒有。
--   語法寫得愈平凡愈好 —— 這支要老闆自己貼進 SQL 編輯器跑。
--
-- Rollback：
--   ALTER TABLE picking_drafts DROP COLUMN IF EXISTS dispatched_at;
--   ALTER TABLE picking_drafts DROP COLUMN IF EXISTS dispatched_by;
--   （兩欄都是本檔新加、沒有任何既有物件依賴它們；status 的 COMMENT 換回
--     20260817000010 那句原文即可，COMMENT 沒有副作用。）
-- ============================================================

ALTER TABLE picking_drafts
  ADD COLUMN IF NOT EXISTS dispatched_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS dispatched_by UUID;

COMMENT ON COLUMN picking_drafts.dispatched_at IS
  '這張草稿把商品清單送到派貨工作台的時間。NULL=還沒送過。⛔ 一旦有值就永遠不清空（含按「重新開啟」）：它是「不能重複轉」的唯一依據，前端送出時下 WHERE dispatched_at IS NULL 並看回傳列數。⚠ 只記「送過商品清單」，不代表已建撿貨單 —— 建單一律在派貨工作台手動完成。';

COMMENT ON COLUMN picking_drafts.dispatched_by IS
  '把這張草稿送到派貨工作台的人（auth.users.id）。⚠ 與 created_by / updated_by 一樣刻意不建外鍵，純稽核用。';

-- ⓘ 刻意寫成一道單行的 COMMENT（不用字串接續、不用 ||）：這支要老闆自己貼進 SQL 編輯器跑，
--   語法愈平凡愈不會出事。作法沿用 20260817000010。
COMMENT ON COLUMN picking_drafts.status IS
  'draft=進行中 / done=已完成（老闆手動按）。兩種情況會變成 done：① 按【📤 送到派貨工作台】把商品清單帶過去（同時寫 dispatched_at）② 按【🔒 收起草稿（不送工作台）】只收起來留底。⚠ status 與 dispatched_at 刻意不連動：status=這張還要不要改（按「重新開啟」可轉回 draft），dispatched_at=這批商品有沒有被帶進工作台過（永不清空）。⛔ 帶過去的只有商品清單，數量一律由派貨工作台自己算（老闆 2026-08-18：「所有的數字店家通通不用帶」）。一張草稿＝一天的撿貨。';
