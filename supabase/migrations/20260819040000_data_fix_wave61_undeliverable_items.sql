-- ============================================================
-- 資料修正：撤回撿貨單 WV260624000206 中「從未送達、貨已回總倉」的明細
--
-- 不改 schema、不改任何函式。只移除 picking_wave_items 中與事實不符的列，
-- 並依系統既有慣例寫入 picking_wave_audit_log（action='item_removed'）。
-- 留成 migration 是為了讓正式庫的人工修正有跡可循。
--
-- ── 背景 ────────────────────────────────────────────────
-- PO2606100406 / G00185-01（排水口分解錠）撿貨單 WV260624000206 派 90 件，
-- 實際只有 65 件送達 10 家店。差額 25 件分成三種完全不同的成因：
--
--   南平店 13 件：送貨單 WAVE-61-S42 **cancelled**（貨從未出車）
--   古華店 11 件：送貨單 WAVE-61-S41 received，出貨 11 / 實收 0，
--                 短少已以 shortage_resolution='restock_hq' 沖回總倉
--   四號店  1 件：送貨單 WAVE-61-S37 shipped 未點收（該店已收攤，不處理）
--
-- 南平 13 ＋ 古華 11 ＝ 24 件，與總倉當時實際庫存 24 件完全吻合。
--
-- ── 為什麼卡住 ──────────────────────────────────────────
-- 「已派量」的算法（20260818000030:174-194）只看 picking_wave_items，
-- **不看送貨單是否取消、是否收到、是否已沖回總倉**：
--     可派 = 進貨 90 − 已派 90 = 0
-- → 貨回到總倉了，卻沒有任何人能再派它。
--   南平 8 位、古華 8 位客人的訂單自 2026-06 起 pending 兩個月無法取貨。
--
-- 古華這筆正是 20260811020000 檔頭描述的痛點本體：
--   「restock_hq 只把短收量沖回總倉庫存，貨帳回來了但沒人重派 ——
--     工作台的需求模型認為該 (po, sku, store) 已派過，不會再邀請派貨」
--   該檔 8/11 上線的 redispatch 會自動補撿貨單，但古華是在那之前處理的；
--   且 shortage_resolution 一旦有值就從異常清單消失，無法再走 redispatch。
--
-- ── 為什麼用刪除、為什麼不用現成功能 ────────────────────
-- · picking_wave_items.qty 有 CHECK (qty > 0)（20260423120002:52）→ 不能改成 0
-- · 撿貨單一旦 shipped，rpc_update_picked_qty / rpc_add_wave_item 全部擋
--   （20260817000020:117-118），且系統**沒有**「移除單一品項」的 RPC，
--   只有取消/刪除整張 —— 那會波及其他 10 家已正常收貨的店
-- · picking_wave_audit_log.wave_item_id 為 ON DELETE SET NULL，刪除不會失敗；
--   該表的 action 清單本就含 'item_removed'，代表移除品項是既有預期行為
--
-- ── 安全閘（兩店條件不同，缺一不動）──────────────────────
--   南平：送貨單 WAVE-61-S42 必須 status='cancelled'
--   古華：送貨單 WAVE-61-S41 必須 status='received'
--         ＋ 該明細 qty_received = 0
--         ＋ shortage_resolution = 'restock_hq'  ← 最關鍵
--   ⛔ 古華第三條不可省：沒有沖回總倉就刪撿貨明細，同一批貨會被派兩次。
--
-- ── 正式庫執行紀錄 ──────────────────────────────────────
-- 逐店個別執行並驗收（每支都附安全閘、驗收與完整 INSERT 回滾指令）：
--   · 南平（wave_item id=1465, qty=13）→ 已移除，其餘列未受影響
--   · 古華（store_id=41, qty=11）      → 見同批執行紀錄
-- 另：PO2606100406 本身在 20260819020000 被改為 partially_received、
--   於 20260819030000 判定誤判而還原為 closed；本次撤回撿貨明細後
--   確實產生可派量，遂再次改為 partially_received 使其進入派貨白名單。
--   兩次改動理由不同：前次「已派 90 = 進貨 90，無貨可派」→ 不該改；
--   本次「已派 66 < 進貨 90，有 24 件待派」→ 該改。
--   ⚠️ 兩店派貨完成後應將該單改回 closed，避免長期掛在進貨待辦誤導收貨。
--
-- ── 根因未修（本 PR 不動）──────────────────────────────
-- 「已派量」應扣除已取消 / 已沖回的送貨單量。這與斷貨自動結案是兩個獨立缺陷，
-- 但症狀相同（貨在總倉卻派不出去），且本缺陷更常見 —— 只要有人取消一張送貨單，
-- 那批貨就永久卡死。需求單：
--   公司\01_進行中\需求暨計畫_斷貨連坐鎖貨根治_2026-08-19.md（範圍待併入本項）
--
-- ── 回滾 ────────────────────────────────────────────────
-- 每次執行都輸出完整 INSERT 還原指令；稽核紀錄的 before_value 亦存有同一份資料。
-- 例（南平）：
--   INSERT INTO picking_wave_items (id,tenant_id,wave_id,sku_id,store_id,qty,
