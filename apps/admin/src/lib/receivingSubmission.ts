// 樓下 iPad 收貨頁（wms/receiving/ipad）「這一次送出要不要沿用上一把冪等鍵」的判斷。
//
// ⛔ 抽成獨立模組不是為了整潔，是因為這條路**會直接壞帳**，必須能單獨被測。
//    改這裡之前先讀完下面整段由來。
//
// ── 由來：2026-08-20 複審抓到的 P0（「少送品項會靜默重複入庫」）────────────
// 送出失敗之後，樓下**不一定會退出畫面**，很可能就地改一改再按一次。
// 前兩版對這件事的處理都不夠：
//
//   v1（沿用同一把鍵，不看內容）
//     第一次其實已經 commit、只是 HTTP 回應斷在路上 → 第二次沿用同一把鍵
//     → 後端認出是重試、回傳第一次那張 GR
//     → **這次改的數字完全不生效，畫面卻是成功的**。
//
//   v2（內容變就換新鍵，靠樂觀鎖接手）← 這一版破功，就是本次的 P0
//     當時的理由是「換新鍵不會重複收貨，因為 qty_received_base 對不上，
//     樂觀鎖會擋」。**這句話只在『第二次還有送那些品項』時成立。**
//     前端的 arrivals 是 `filter(received > 0)` 現算的，只包含這次有填數量的品項；
//     後端樂觀鎖也只逐項比對**有送進來的品項**。
//     ⇒ 第一次送 A=5 已 commit、回應斷掉；樓下不確定 A 有沒有問題，
//       把 A 清成 0、改填 B=5 再送 → 第二次的 payload 裡根本沒有 A
//       → A 不會被任何一道防線檢查 → B 入庫成功、畫面顯示成功，
//         而 A 早在第一次就已經悄悄入過一次帳。**系統從頭到尾沒吵一聲。**
//
// ── 現在的規則（v3）：送出失敗後，內容改了就不准送 ────────────────────────
// 關鍵認知：**送出失敗之後，使用者手上那份畫面已經不可信**
// （可能成功了、可能沒成功，前端分不出來 —— supabase-js 對「伺服器回錯誤」
//  與「網路斷掉」都是回 `{ error }`，⛔ 不要試圖用 error 的形狀去猜有沒有 commit，
//  猜錯的代價就是上面那筆靜默壞帳）。
// 讓他改內容再送，本質上是在猜。唯一安全的動作是**重讀現況**：
// 退出去重新點這張採購單，讓 openPO 重撈最新的 qty_received。
//
//   ⇒ 沒送過（prev = null）           → first ：新的一把鍵，正常送
//   ⇒ 送過、內容一模一樣             → retry ：沿用同一把鍵，後端回既有 GR
//                                              （「先前已經收過了」的成功畫面）
//   ⇒ 送過、內容不一樣               → blocked：擋下，叫人重新載入這張單
//
// ⚠️ 代價（誠實記著，不要之後有人以為是 bug）：
//    有些失敗其實**確定沒有 commit**（例如後端回「品項不屬於這張採購單」、
//    樂觀鎖擋下…），這些情況下本來可以就地改一改再送，現在也要重新載入一次。
//    多按兩下 vs. 靜默重複入庫，選前者。
//
// ⚠️ 這道防線只在前端。後端還是有兩道（冪等鍵、逐項樂觀鎖），但**後端那兩道
//    都看不到「第二次沒送進來的品項」**，所以這一支是目前唯一擋得住上面那個
//    情境的東西。⛔ 誰要把它拿掉，請先把後端改成能檢查全品項的 base 快照。

/** 上一次送出的冪等鍵，以及送出當時的內容（兩者永遠一起存、一起清）。 */
export type Submission = { id: string; payload: string };

export type SubmissionDecision =
  /** 這是全新的一次送出 → 用 id 這把新鍵。 */
  | { kind: "first"; id: string }
  /** 同一份內容重送 → 沿用上一把鍵，讓後端認得出是重試。 */
  | { kind: "retry"; id: string }
  /** 上一次結果不明、而內容又改了 → 不准送，請重新載入這張單。 */
  | { kind: "blocked" };

/** blocked 時給樓下看的話。放這裡是為了讓測試對得到同一份字串。 */
export const SUBMISSION_BLOCKED_MESSAGE =
  "上一筆可能已經送出去了（我們這邊分不出來），所以不能就這樣改個數字再送一次 —— " +
  "那有機會把同一批貨收兩次。請按下面的「重新載入這張單」，看最新的已收數量再重收一次。";

/**
 * 決定這一次送出要用哪一把冪等鍵，或是根本不該送。
 *
 * @param prev   上一次送出留下的 { id, payload }；沒送過就是 null
 * @param payload 這一次要送的內容（呼叫端自己序列化，本函式只比對字串相不相等）
 * @param newId  產生新鍵的函式（注入進來才測得動）
 */
export function decideSubmission(
  prev: Submission | null,
  payload: string,
  newId: () => string,
): SubmissionDecision {
  if (!prev) return { kind: "first", id: newId() };
  if (prev.payload === payload) return { kind: "retry", id: prev.id };
  return { kind: "blocked" };
}
